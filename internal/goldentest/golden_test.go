// scenarioByName finds one of promtest.Scenarios by name, or fails the
// test: every name this file uses names a real scenario.
func scenarioByName(t *testing.T, name string) promtest.Scenario {
	t.Helper()
	for _, s := range promtest.Scenarios {
		if s.Name == name {
			return s
		}
	}
	t.Fatalf("no scenario named %q", name)
	return promtest.Scenario{}
}

// compareGolden reads the golden file at path and compares it with got. It
// names `make update-testdata` in both of its failure messages, so that a
// missing or a different golden file always tells the reader how to fix it.
func compareGolden(path string, got []byte) error {
	want, err := os.ReadFile(path)
	if err != nil {
		return fmt.Errorf("reading %s: %w; run `make update-testdata` to create it", path, err)
	}
	if !bytes.Equal(got, want) {
		return fmt.Errorf("%s does not match the generated bytes; run `make update-testdata` and review the change", path)
	}
	return nil
}

// TestGoldenSnapshots runs each of the six scenarios through Snapshot and
// compares the result with its golden file.
func TestGoldenSnapshots(t *testing.T) {
	for _, scenario := range promtest.Scenarios {
		t.Run(scenario.Name, func(t *testing.T) {
			got, err := Snapshot(context.Background(), scenario)
			if err != nil {
				t.Fatalf("Snapshot(%s): %v", scenario.Name, err)
			}
			path, err := SnapshotPath(scenario.Name)
			if err != nil {
				t.Fatalf("SnapshotPath(%s): %v", scenario.Name, err)
			}
			if err := compareGolden(path, got); err != nil {
				t.Fatal(err)
			}
		})
	}
}

// TestGoldenDataFiles runs each of the four scenarios with a golden data
// file through Snapshot and DataFile, in each language, and compares the
// result with its golden file.
func TestGoldenDataFiles(t *testing.T) {
	for _, name := range DataFileScenarios {
		scenario := scenarioByName(t, name)
		snap, err := Snapshot(context.Background(), scenario)
		if err != nil {
			t.Fatalf("Snapshot(%s): %v", name, err)
		}
		for _, lang := range catalog.Languages() {
			t.Run(name+"/"+string(lang), func(t *testing.T) {
				got, err := DataFile(snap, lang)
				if err != nil {
					t.Fatalf("DataFile(%s, %s): %v", name, lang, err)
				}
				path, err := DataFilePath(name, lang)
				if err != nil {
					t.Fatalf("DataFilePath(%s, %s): %v", name, lang, err)
				}
				if err := compareGolden(path, got); err != nil {
					t.Fatal(err)
				}
			})
		}
	}
}

// fileStems reads dir and returns the stem of every file directly inside it
// whose extension is ext, sorted. A file of another extension, or one in a
// subfolder, fails the test: neither folder holds anything else.
func fileStems(t *testing.T, dir, ext string) []string {
	t.Helper()
	entries, err := os.ReadDir(dir)
	if err != nil {
		t.Fatalf("reading %s: %v", dir, err)
	}
	var stems []string
	for _, entry := range entries {
		if entry.IsDir() {
			t.Fatalf("%s: unexpected subfolder %s", dir, entry.Name())
		}
		if filepath.Ext(entry.Name()) != ext {
			t.Fatalf("%s: unexpected file %s", dir, entry.Name())
		}
		stems = append(stems, strings.TrimSuffix(entry.Name(), ext))
	}
	sort.Strings(stems)
	return stems
}

// jsonStems reads dir and returns the stem of every ".json" file directly
// inside it, sorted. A non-".json" entry, or one in a subfolder, fails the
// test: neither folder holds anything else.
func jsonStems(t *testing.T, dir string) []string {
	t.Helper()
	return fileStems(t, dir, ".json")
}

