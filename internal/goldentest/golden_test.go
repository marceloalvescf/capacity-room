// unifiedRequestsLimitsQueries returns the lines of a golden queries file
// whose query mentions the unified requests or limits metric: the four
// lines the four probes of TestQueriesTellTheProbesApart pins down.
func unifiedRequestsLimitsQueries(lines []string) []string {
	var out []string
	for _, line := range lines {
		if strings.Contains(line, "kube_pod_container_resource_requests{") ||
			strings.Contains(line, "kube_pod_container_resource_limits{") {
			out = append(out, line)
		}
	}
	return out
}

// TestQueriesTellTheProbesApart proves that the four probes of the unified
// requests and limits capability are told apart in the golden queries
// files: two lines carry resource="cpu" and two carry resource="memory",
// and the four lines are pairwise different — never four labels the
// scenario's own fixture could have answered interchangeably.
func TestQueriesTellTheProbesApart(t *testing.T) {
	for _, scenario := range promtest.Scenarios {
		t.Run(scenario.Name, func(t *testing.T) {
			path, err := QueriesPath(scenario.Name)
			if err != nil {
				t.Fatalf("QueriesPath(%s): %v", scenario.Name, err)
			}
			data, err := os.ReadFile(path)
			if err != nil {
				t.Fatalf("reading %s: %v", path, err)
			}
			lines := strings.Split(strings.TrimRight(string(data), "\n"), "\n")

			found := unifiedRequestsLimitsQueries(lines)
			if len(found) != 4 {
				t.Fatalf("found %d unified requests/limits lines, want 4: %v", len(found), found)
			}

			seen := make(map[string]bool, 4)
			cpu, memory := 0, 0
			for _, line := range found {
				if seen[line] {
					t.Fatalf("line %q repeated among the four unified requests/limits lines", line)
				}
				seen[line] = true
				switch {
				case strings.Contains(line, `resource="cpu"`):
					cpu++
				case strings.Contains(line, `resource="memory"`):
					memory++
				default:
					t.Fatalf("line %q names neither resource=\"cpu\" nor resource=\"memory\"", line)
				}
			}
			if cpu != 2 || memory != 2 {
				t.Fatalf("cpu=%d memory=%d, want 2 and 2: %v", cpu, memory, found)
			}
		})
	}
}

// TestGoldenFoldersHoldNoStranger checks that testdata/snapshot/,
// testdata/queries/, and template/tests/capacity/fixtures/command/ hold
// exactly the files the scenario lists name, and nothing else.
func TestGoldenFoldersHoldNoStranger(t *testing.T) {
	t.Run("snapshot", func(t *testing.T) {
		anyPath, err := SnapshotPath("direct-complete")
		if err != nil {
			t.Fatalf("SnapshotPath: %v", err)
		}
		var want []string
		for _, s := range promtest.Scenarios {
			want = append(want, s.Name)
		}
		sort.Strings(want)

		got := jsonStems(t, filepath.Dir(anyPath))
		if !reflect.DeepEqual(got, want) {
			t.Errorf("testdata/snapshot/ holds %v, want %v", got, want)
		}
	})

	t.Run("data files", func(t *testing.T) {
		anyPath, err := DataFilePath("direct-complete", catalog.PortugueseBrazil)
		if err != nil {
			t.Fatalf("DataFilePath: %v", err)
		}
		var want []string
		for _, name := range DataFileScenarios {
			for _, lang := range catalog.Languages() {
				want = append(want, name+"."+string(lang))
			}
		}
		sort.Strings(want)

		got := jsonStems(t, filepath.Dir(anyPath))
		if !reflect.DeepEqual(got, want) {
			t.Errorf("fixtures/command/ holds %v, want %v", got, want)
		}
	})

	t.Run("queries", func(t *testing.T) {
		anyPath, err := QueriesPath("direct-complete")
		if err != nil {
			t.Fatalf("QueriesPath: %v", err)
		}
		var want []string
		for _, s := range promtest.Scenarios {
			want = append(want, s.Name)
		}
		sort.Strings(want)

		got := fileStems(t, filepath.Dir(anyPath), ".txt")
		if !reflect.DeepEqual(got, want) {
			t.Errorf("testdata/queries/ holds %v, want %v", got, want)
		}
	})
}

// TestSnapshotIsTheSameTwice proves that nothing of the test server's
// address, whose port changes at every run, reaches the encoded snapshot.
func TestSnapshotIsTheSameTwice(t *testing.T) {
	scenario := scenarioByName(t, "direct-complete")

	first, err := Snapshot(context.Background(), scenario)
	if err != nil {
		t.Fatalf("Snapshot, first run: %v", err)
	}
	second, err := Snapshot(context.Background(), scenario)
	if err != nil {
		t.Fatalf("Snapshot, second run: %v", err)
	}

	if !bytes.Equal(first, second) {
		t.Fatal("Snapshot gave different bytes on two runs of the same scenario")
	}
}

// withoutAddressFields decodes a snapshot and clears the two fields the
// brief says are allowed to differ between direct-complete and one of its
// stand-ins: scope.discovered_values and settings.endpoint_type.
func withoutAddressFields(t *testing.T, data []byte) snapshot.Snapshot {
	t.Helper()
	snap, err := snapshot.Decode(data)
	if err != nil {
		t.Fatalf("Decode: %v", err)
	}
	snap.Scope.DiscoveredValues = nil
	snap.Report.Settings.EndpointType = ""
	return snap
}

// TestOtherScenariosGiveTheSameDocument checks that grafana-authenticated
// and thanos-multicluster, which have no golden data file of their own,
// build the same document as direct-complete in each language, and that
// their snapshots differ from it only in scope.discovered_values and
// settings.endpoint_type.
func TestOtherScenariosGiveTheSameDocument(t *testing.T) {
	baselineScenario := scenarioByName(t, "direct-complete")
	baselineSnap, err := Snapshot(context.Background(), baselineScenario)
	if err != nil {
		t.Fatalf("Snapshot(direct-complete): %v", err)
	}
	baselineComparable := withoutAddressFields(t, baselineSnap)

	for _, name := range []string{"grafana-authenticated", "thanos-multicluster"} {
		t.Run(name, func(t *testing.T) {
			scenario := scenarioByName(t, name)
			snap, err := Snapshot(context.Background(), scenario)
			if err != nil {
				t.Fatalf("Snapshot(%s): %v", name, err)
			}

			scenarioComparable := withoutAddressFields(t, snap)
			if !reflect.DeepEqual(scenarioComparable, baselineComparable) {
				t.Errorf("%s snapshot differs from direct-complete beyond scope.discovered_values and settings.endpoint_type", name)
			}

			for _, lang := range catalog.Languages() {
				gotDoc, err := DataFile(snap, lang)
				if err != nil {
					t.Fatalf("DataFile(%s, %s): %v", name, lang, err)
				}
				wantDoc, err := DataFile(baselineSnap, lang)
				if err != nil {
					t.Fatalf("DataFile(direct-complete, %s): %v", lang, err)
				}
				if !bytes.Equal(gotDoc, wantDoc) {
					t.Errorf("%s (%s) document differs from direct-complete", name, lang)
				}
			}
		})
	}
}

// TestGoldenFailureNamesTheCommand checks that compareGolden's failure
// message names `make update-testdata`, both when the golden file holds
// different bytes and when it is missing.
func TestGoldenFailureNamesTheCommand(t *testing.T) {
	t.Run("different bytes", func(t *testing.T) {
		dir := t.TempDir()
		path := filepath.Join(dir, "direct-complete.json")
		if err := os.WriteFile(path, []byte("replaced by another text\n"), 0o600); err != nil {
			t.Fatalf("writing %s: %v", path, err)
		}

		err := compareGolden(path, []byte("the freshly generated bytes\n"))
		if err == nil {
			t.Fatal("compareGolden = nil error, want one")
		}
		if !strings.Contains(err.Error(), "make update-testdata") {
			t.Fatalf("error = %q, want it to name make update-testdata", err.Error())
		}
	})

	t.Run("missing file", func(t *testing.T) {
		path := filepath.Join(t.TempDir(), "missing.json")

		err := compareGolden(path, []byte("anything"))
		if err == nil {
			t.Fatal("compareGolden = nil error, want one")
		}
		if !strings.Contains(err.Error(), "make update-testdata") {
			t.Fatalf("error = %q, want it to name make update-testdata", err.Error())
		}
	})
}
